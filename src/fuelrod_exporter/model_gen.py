def filter_objects(all_objects: List[str], excluded_patterns: List[str], included_objects: List[str] = None) -> List[
    str]:
    """
    Filter database objects based on exclusion patterns and explicit inclusions using wildcard matching.

    Supports Unix shell-style wildcards:
    - * matches everything
    - ? matches any single character
    - [seq] matches any character in seq
    - [!seq] matches any character not in seq

    Examples:
    - "temp_*" excludes all objects starting with "temp_"
    - "*_backup" excludes all objects ending with "_backup"
    - "test_table_?" excludes test_table_1, test_table_2, etc.
    """
    if included_objects is None:
        included_objects = []

    # Start with all objects
    filtered_objects = list(all_objects)
    excluded_objects = []

    # Apply exclusion patterns
    if excluded_patterns:
        temp_filtered = []
        for obj in filtered_objects:
            is_excluded = False
            for pattern in excluded_patterns:
                if fnmatch.fnmatch(obj, pattern):
                    logger.debug(f"Object '{obj}' excluded by pattern '{pattern}'")
                    is_excluded = True
                    excluded_objects.append((obj, pattern))
                    break

            if not is_excluded:
                temp_filtered.append(obj)

        filtered_objects = temp_filtered

    # Add explicitly included objects (even if they were excluded by patterns)
    for obj in included_objects:
        if obj not in filtered_objects and obj in all_objects:
            filtered_objects.append(obj)
            logger.debug(f"Object '{obj}' explicitly included")

    # Remove duplicates while preserving order
    filtered_objects = list(dict.fromkeys(filtered_objects))

    logger.info(
        f"Object filtering results: {len(filtered_objects)} included, {len(excluded_objects)} excluded from {len(all_objects)} total")

    if excluded_objects:
        logger.debug("Excluded objects details:")
        for obj, pattern in excluded_objects:
            logger.debug(f"  - '{obj}' (pattern: '{pattern}')")

    return filtered_objects


